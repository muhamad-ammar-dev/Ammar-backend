// سعر البند التقريبي للمهنة (مع fallback ذكي لأي بند جديد)
function getDefaultPrice(categoryName, itemKey) {
  const cat = DEFAULT_PRICES[String(categoryName).trim()];
  if (cat && itemKey in cat) return cat[itemKey];
  return null;
}

// حساب السعر التقديري لطلب: Σ (سعر البند التقريبي × الكمية)
function estimateRequestPrice(categoryName, orderDetails) {
  const total = { estimated: 0, count: 0 };
  if (!orderDetails || typeof orderDetails !== "object") return total;
  for (const [key, qty] of Object.entries(orderDetails)) {
    if (!Number.isFinite(Number(qty)) || Number(qty) <= 0) continue;
    const unitPrice = getDefaultPrice(categoryName, key);
    if (unitPrice == null) continue;
    total.estimated += unitPrice * Number(qty);
    total.count += 1;
  }
  total.estimated = Math.round(total.estimated * 100) / 100;
  return total;
}

// أرخص بند في المهنة (سعر "يبدأ من")
function getMinPrice(categoryName) {
  const cat = DEFAULT_PRICES[String(categoryName).trim()];
  if (!cat) return null;
  const values = Object.values(cat).map(Number).filter(Number.isFinite);
  return values.length ? Math.min(...values) : null;
}

